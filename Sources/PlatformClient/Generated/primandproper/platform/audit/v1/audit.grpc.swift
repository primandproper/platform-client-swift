// Package primandproper.platform.audit.v1 is the wire schema for reading the
// audit log: one entry by id, a page of them, and a verification of one scope's
// hash chain.
//
// This file is shipped inside the published Go module, and it is the file
// itself that is shipped -- not a copy for you to keep in sync. A consumer puts
// the module's proto directories on protoc's path and imports this file by its
// canonical name, exactly as identity.proto and filtering.proto already work:
//
//	PLATFORM_PROTO := $(shell go list -m -f '{{.Dir}}' github.com/primandproper/platform-go/v15)
//
//	protoc --proto_path proto/ \
//	    --proto_path $(PLATFORM_PROTO)/audit/proto \
//	    --proto_path $(PLATFORM_PROTO)/filtering/proto \
//	    --go_opt=Mprimandproper/platform/audit/v1/audit.proto=github.com/primandproper/platform-go/v15/audit/auditpb \
//	    $(CONSUMER_PROTO_FILES)   # the platform files deliberately absent from that list
//
// Go links against the bindings this module already generated, in
// github.com/primandproper/platform-go/v15/audit/auditpb. Swift, TypeScript and
// Kotlin have no such bindings to link against and generate this file directly,
// which is the whole point of shipping the schema.
//
// Field numbers are the compatibility promise, across every language a consumer
// generates into. Numbers are never reused and never repurposed: a field that
// goes away is reserved.
//
// # There is no scope field, and there cannot be one
//
// audit.Query carries a scope selector in which nil means every tenant's
// events, and that field's own documentation says getting it backwards is a
// cross-tenant disclosure rather than a wrong answer. Held in a process it is a
// capability an operator built deliberately, by constructing a Reader and
// passing the query themselves. On a wire it would be a capability every caller
// has, in a field a client fills in.
//
// So the scope is bound off the connection by audit/grpc, and the name "scope"
// is reserved in every request message here. That is not a comment asking the
// next author not to add one -- protoc refuses the field, in this repository
// and in a consumer's fork of the schema alike.
//
// The entry messages carry no scope either. Every entry a response returns
// belongs to the scope the connection resolved, so the field would tell a
// client something it supplied, and its absence is what makes a converter
// unable to read one back out of a request.
//
// AuditAdministrationService is the one place a request names a tenant, and it
// is a service of its own for exactly the reason above. There the capability
// is the method: a caller reaches GetAnyEntry or ListAnyEntries only by holding
// the permission audit/grpc's Permissions puts on them, which nothing grants
// by default, and every call is recorded in the caller's own chain before it is
// answered. A field on AuditService's messages would hand the same reach to
// everybody who may read their own log; a method of its own hands it to the
// operators a deployment named, and a policy that leaves them out is refused
// by the enforcer's fail-closed rule rather than widened. Its messages still
// reserve "scope" -- the tenant it names is owner_id, which is what a
// tenancy.Scope stores -- and its entries carry the owner they belong to,
// because an answer spanning tenants is the one answer that cannot leave it
// implied.
//
// # There is no recording RPC
//
// audit.Recorder is absent from this service on purpose, and the reason is on
// the interface itself: an audit entry that can commit while the change it
// describes rolls back -- or the reverse -- is not a record of what happened,
// and no amount of retrying fixes it after the fact. A recording that crossed a
// connection would commit in this service's transaction rather than in the
// caller's, which is the one thing the whole package exists to prevent.
//
// What crosses is the reading, and Verify is the reason it is worth crossing:
// walking a scope's chain and reporting the first break is the capability a
// hand-written log reader never gets around to, and the one most worth calling
// remotely and on a schedule.

