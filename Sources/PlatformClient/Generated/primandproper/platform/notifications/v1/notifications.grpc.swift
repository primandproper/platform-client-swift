    /// means of communication with the remote peer.
    ///
    /// > Source IDL Documentation:
    /// >
    /// > NotificationsService is the bell icon and the device registry.
    /// > 
    /// > Every RPC acts on the caller's own rows and on nobody else's, and that is a
    /// > property of the schema rather than of a check: no request here names a
    /// > principal, the name is reserved on every one of them, and the service reads
    /// > the recipient off the caller the consumer's interceptor resolved. Every
    /// > method still requires a grant -- see the Permissions map in
    /// > notifications/grpc -- because "the caller owns the row" answers which rows,
    /// > not whether this deployment offers the call at all.
    /// > 
    /// > # The methods that are not here
    /// > 
    /// > Not every method across notifications.Inbox and notifications.Registry is an
    /// > RPC, and the absences are different shapes of machinery rather than instances
    /// > of one. Each argues its own case on its Store method, which is
    /// > where a reader of the Go API is standing when the question occurs to them.
    /// > 
    /// > CreateNotification is the transactional companion. It files a notification in
    /// > the caller's transaction so that it commits with the thing the notification
    /// > is about -- the order, the invitation, the failed payment -- and an RPC moves
    /// > that write into a transaction of its own, at a moment the caller does not
    /// > choose. What you get is a refused order that has already told somebody it
    /// > shipped, which is a failure running in the direction the user can see. It is
    /// > the same fact audit.Recorder states about an audit entry, and the reason that
    /// > method takes a transaction too. A process that wants to notify somebody about
    /// > something it did not cause is describing an RPC of its own, whose handler
    /// > owns the transaction the write belongs in.
    /// > 
    /// > ListDevicesByPrincipals is the internal fan-out: one query for the tokens a
    /// > notification addressed to thirty people has to be pushed to, rather than
    /// > thirty round trips. It names other people's principals by construction, which
    /// > is exactly the request field this schema reserves the name of, and it is
    /// > documented as being passed the transaction the inbox rows were written in --
    /// > a caller no RPC has.
    /// > 
    /// > InvalidateDeviceToken is the provider callback hook, and it is the one
    /// > absence here that is a security property rather than a shape. It removes a
    /// > token whoever it belongs to, taking neither a scope nor a transaction,
    /// > because what APNs and FCM hand back on a dead push is a token and nothing
    /// > else. Wired as mobile.WithTokenInvalidator it is a sender acting on a verdict
    /// > a provider actually returned; published as an RPC it is a call that deletes
    /// > any handset's registration in any tenant on the say-so of a caller claiming
    /// > the provider said so.
    /// > 
    /// > DeleteNotificationsForPrincipal and DeleteDevicesForPrincipal are the last
    /// > shape and the only one that is two methods, because it is one shape over two
    /// > tables: the erasure. Each names a principal and destroys every row under it,
    /// > and neither has a client. A person clearing a notification is calling
    /// > ArchiveNotification, which stamps one row they named and leaves it readable;
    /// > one signing a handset out is calling RevokeDevice, which removes one
    /// > registration they named. What these two answer is a dataprivacy request an
    /// > operator has already confirmed, arriving through notifications/privacy, and
