// Package primandproper.platform.notifications.v1 is the wire schema for the
// two halves of notifications: the in-app inbox a bell icon reads, and the
// registry of handsets a push is addressed to.
//
// Most of the methods across notifications.Inbox and notifications.Registry are
// here and the rest deliberately are not. The service comment at the bottom of
// this file names each absence and says which shape of machinery it is.
//
// This file is shipped inside the published Go module, and it is the file
// itself that is shipped -- not a copy for you to keep in sync. A consumer puts
// the module's proto directories on protoc's path and imports this file by its
// canonical name, exactly as identity.proto and filtering.proto already work:
//
//	PLATFORM_PROTO := $(shell go list -m -f '{{.Dir}}' github.com/primandproper/platform-go/v15)
//
//	protoc --proto_path proto/ \
//	    --proto_path $(PLATFORM_PROTO)/notifications/proto \
//	    --proto_path $(PLATFORM_PROTO)/filtering/proto \
//	    --go_opt=Mprimandproper/platform/notifications/v1/notifications.proto=github.com/primandproper/platform-go/v15/notifications/notificationspb \
//	    $(CONSUMER_PROTO_FILES)   # the platform files deliberately absent from that list
//
// Field numbers are the compatibility promise, across every language a consumer
// generates into. Numbers are never reused and never repurposed: a field that
// goes away is reserved.
//
// # topic is a string and platform is an enum, and the difference is whose set it is
//
// [Notification]'s topic is opaque. The catalog of them -- order.shipped,
// invite.received, whatever an application groups, mutes and routes by -- is
// the consumer's, and notifications validates none of it, so a generated enum
// would put that vocabulary on this module's release cadence. Adding
// "subscription.lapsed" would become a platform-go release. It is the same
// ruling issuereports.Kind and comments.TargetType are under.
//
// [DevicePlatform] is the opposite case and is therefore an enum. The set is
// closed by what notifications/mobile can actually route to, which is this
// module's fact rather than an application's: a token stored under a platform
// no sender serves is a row that can never be delivered to and will never be
// pruned, because the feedback that prunes rows comes from the provider that
// rejected them. A string there would let a client register "IOS " and get a
// row nothing ever reads.
//
// # What is not here, and why
//
// No scope field and no principal field, anywhere, and both names are reserved
// so there cannot be one.
//
// The scope is the module-wide rule: a tenant a client could name is a
// cross-tenant read hiding behind a request field. See identity.proto, which
// says it at greater length.
//
// The principal is this schema's own, and on this surface it is the sharper of
// the two. Every row here is addressed to one person -- a notification is not a
// row the rest of their tenant may read, and a device token is not a handset the
// rest of their tenant may revoke -- so a request naming a principal is a
// request to read somebody else's bell icon. It comes off the caller the
// consumer's interceptor put on the context, and every statement behind these
// RPCs binds it, which is what makes "may this caller reach this row" a property
// of the query rather than a check somebody has to remember to write. The
// responses carry no principal either, because every row they return belongs to
// the caller and the field would be telling a client something it supplied.
//
// Reserving the names rather than only saying so is audit.proto's pattern and
// is the half that holds: `reserved "scope", "principal";` is a schema protoc
// refuses those fields into, in this repository and in a consumer's fork of the
// file alike, whereas a comment is a request to the next author.
//
// No device token on any response. It travels in on exactly one message --
// [DeviceRegistrationInput] -- and in one direction only, and [Device] has
// nowhere to put one. A handset knows its own token, because it minted it and
// just sent it, so no read here exists to tell it; what a device list is for is
// the other question, which is what is registered, on what, and when it was
// last seen. Handing the set back the other way would make "list my devices"
// the call that harvests every push address an account holds, and the row it
// would harvest is the one notifications documents as the natural key.
//
// No unread count of its own. It is on the pagination of
// [ListUnreadNotificationsResponse], filtered rather than paged, which is the
// number a badge renders and is already the answer that read produces.

