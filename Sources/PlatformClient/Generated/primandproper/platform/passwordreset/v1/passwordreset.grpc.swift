// Package primandproper.platform.passwordreset.v1 is the wire schema for the
// one flow a person who cannot sign in still needs: proving they own the
// address an account was registered with, and choosing a new password with that
// proof.
//
// This file is shipped inside the published Go module, and it is the file itself
// that is shipped -- not a copy for you to keep in sync. A consumer puts the
// module's proto directories on protoc's path and imports this file by its
// canonical name, exactly as signin.proto and filtering.proto already work:
//
//	PLATFORM_PROTO := $(shell go list -m -f '{{.Dir}}' github.com/primandproper/platform-go/v14)
//
//	protoc --proto_path proto/ \
//	    --proto_path $(PLATFORM_PROTO)/authentication/passwordreset/proto \
//	    --go_opt=Mprimandproper/platform/passwordreset/v1/passwordreset.proto=github.com/primandproper/platform-go/v14/authentication/passwordreset/passwordresetpb \
//	    $(CONSUMER_PROTO_FILES)   # the platform file deliberately absent from that list
//
// Field numbers are the compatibility promise, across every language a consumer
// generates into. Numbers are never reused and never repurposed: a field that
// goes away is reserved.
//
// # Why it is its own file rather than more RPCs on signin.proto
//
// signin.proto says it, of this flow by name: passkeys, password reset and
// session management are each "a flow of its own over an engine this module
// already ships, and each is its own file rather than a branch in this one".
// The reason shows in the authority. Every request here carries a mailed secret
// or an address and nothing else -- there is no caller, and there cannot be one,
// because the whole premise is somebody who cannot sign in. Sign-in's schema has
// RPCs that need a principal, and a file where many of the messages answer to
// one and none of these do would be a file whose rules have to be
// restated per message.
//
// # The three refusals, and why they are told apart
//
// A link that cannot be spent is expired, already used, or was never a link, and
// this schema keeps them distinct where almost everything else in this module
// collapses such a set. The argument is the store's and it does not stop at the
// transport: the secret is high-entropy, so learning which of the three happened
// requires already holding the token. Telling somebody with a day-old link that
// it expired is worth more than the nothing an attacker learns from it.
//
// The one place that argument does not reach is [RequestPasswordResetRequest],
// which carries an address rather than a secret. There the answer is identical
// whoever holds it, and the response is empty so that it can stay that way.
//
// # What is not here, and why
//
// No scope field, anywhere, and the name is reserved so there cannot be one.
// identity.proto and signin.proto give the reason at greater length: a scope a
// client could name is a cross-tenant read hiding behind a request field. It
// matters here for signin.proto's reason exactly -- nobody on these requests has
// been authenticated, so the directory a reset is made against comes off the
// connection rather than off anything a client sends.
//
// No hashed password in either direction, and the plaintext travels once, in
// [CompletePasswordResetRequest]. It is what makes this service's transport
// security a requirement rather than a recommendation.
//
// No token in any response. The secret this flow mints travels to the person it
// is about, in mail the consumer sends; it arrives back here as a request field
// on the RPCs that answer a link, which is the one direction a token travels
// on any schema in this module.
//
// No user, anywhere. A reset names an address on the way in and nothing on the
// way out, and [VerifyPasswordResetTokenResponse] deliberately does not say whom
// the link is for -- see that message.
//
// No token minted at the end. Completing a reset does not sign anybody in: the
// door for that is signin.proto's, with the password that was just chosen. And
// completing a reset does not end the sessions the account already has, which is
// the same behaviour signin's UpdatePassword has and is the consumer's to change
// -- signin.Service.RevokeRefreshTokensForSubject is the call, in whatever
// answers this one.

