// Package primandproper.platform.passkeys.v1 is the wire schema for passkeys:
// enrolling one, signing in with one, and the list and archive a settings page
// offers.
//
// This file is shipped inside the published Go module, and it is the file
// itself that is shipped, as signin.proto is. A consumer puts the module's
// proto directories on protoc's path and imports it by its canonical name:
//
//	PLATFORM_PROTO := $(shell go list -m -f '{{.Dir}}' github.com/primandproper/platform-go/v14)
//
//	protoc --proto_path proto/ \
//	    --proto_path $(PLATFORM_PROTO)/authentication/passkeys/proto \
//	    --proto_path $(PLATFORM_PROTO)/authentication/signin/proto \
//	    --proto_path $(PLATFORM_PROTO)/identity/proto \
//	    --proto_path $(PLATFORM_PROTO)/filtering/proto \
//	    --go_opt=Mprimandproper/platform/passkeys/v1/passkeys.proto=github.com/primandproper/platform-go/v14/authentication/passkeys/passkeyspb \
//	    --go_opt=Mprimandproper/platform/signin/v1/signin.proto=github.com/primandproper/platform-go/v14/authentication/signin/signinpb \
//	    $(CONSUMER_PROTO_FILES)
//
// Go links against the bindings in
// github.com/primandproper/platform-go/v14/authentication/passkeys/passkeyspb.
//
// Field numbers are the compatibility promise. Numbers are never reused and
// never repurposed: a field that goes away is reserved.
//
// # The token is sign-in's
//
// FinishLogin answers with signin.v1's IssuedToken, not a message of its own.
// A passkey is another way to prove who somebody is, and what it proves them
// into is the same sign-in a password proves them into: the same lifetimes,
// the same claims, the same refresh token family, the same ExchangeRefreshToken
// and SignOut. A second token message would be a second token stack, which is
// the state this schema exists to end.
//
// # The ceremony travels as JSON
//
// Every begin answers with the options a browser hands to
// navigator.credentials.create or navigator.credentials.get, and every finish
// takes what the browser handed back, both as the JSON the WebAuthn
// specification defines, carried in a bytes field. They are not re-described
// here as messages: the specification owns their shape, it adds fields, and a
// relying party that re-encoded them would be one more place for a field to be
// dropped on the way to a browser that needed it. The options are exactly what
// github.com/go-webauthn/webauthn renders — a publicKey member, base64url for
// every binary value — which is what a browser's parseCreationOptionsFromJSON
// and parseRequestOptionsFromJSON read.
//
// # What is not here, and why
//
// No scope field, anywhere, and the name is reserved so there cannot be one.
// The login half is anonymous, so its scope comes off the connection exactly
// as sign-in's does, and a field would be one an anonymous caller fills in.
//
// No user field on the self-service RPCs. Enrolling, listing and archiving are
// about the caller and nobody else, so the subject comes off the principal,
// and a request that could name somebody would be a request that could add a
// way into their account.
//
// No public key and no sign count on a Passkey. Neither is a secret, and
// neither is anything a settings page renders; the sign count in particular is
// the relying party's clone detection, and a client that could read it would
// be reading the one number an attacker with a cloned key would want.
//
// No separate discoverable RPCs. A login that names no username is the
// discoverable one — the passkey the person chooses names them — and it is the
// same two RPCs with the field empty. A username sent to a deployment that
// offers only the discoverable login is refused as a request to correct.

