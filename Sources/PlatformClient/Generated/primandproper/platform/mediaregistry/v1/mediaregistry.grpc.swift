//
// # Nothing here is the consumer's noun
//
// An object is bytes in a bucket and the row that says whose they are. Every
// rule an application has about them is a value rather than a shape -- which
// types it accepts, how large, where in the bucket they go, what it meters --
// and mediaregistry/grpc takes each of those as an option with a default. What
// an object is *for* is the consumer's, and it stays theirs: an avatar, a
// receipt, an article's photo. The one place this file touches that vocabulary is
// [Subject], and it touches it only as an opaque pair of strings.
//
// # What a caller may attach an object to
//
// Upload and record may attach an object to the caller's own user subject, or
// to nothing. This service cannot know whether article 123 is the caller's, so it
// does not let a caller say so: an attachment to one of the consumer's nouns
// goes through the consumer's own RPC, which authorizes the subject and calls
// mediaregistry.StoreAndRecord with it.
//
// # Refusals say nothing
//
// An object that does not exist, one in another tenant, and one the caller is
// not entitled to are one answer: NOT_FOUND. The same answer goes to a caller
// who tries to attach an object to somebody else, or to register a key outside
// the part of the bucket that is theirs. Separating them would be an oracle,
// and it is the answer mediaregistry/http's serve route already gives.
//
// # What is not here
//
// No scope field, anywhere, and the reservation is what makes that a schema
// protoc enforces rather than a comment somebody can add a field beneath. The
// tenant comes off the caller the consumer's authentication resolved.
//
// No owner on any write. An object belongs to whoever sent it, and an owner a
// client could name is an upload filed under somebody else's quota.
//
// No key and no bucket on an upload. Where the bytes go is the deployment's key
// layout, applied to the caller; a key a client could name is a client choosing
// whose objects it overwrites.
//
// No byte read. mediaregistry/http's guarded serve is where an object's bytes
// come back, because a range is what an image tag and a video player send and
// an RPC does not have one.

